import seaborn as sns
import matplotlib.pyplot as plt

# Assuming new_df contains only the 4 features
new_df = filtered_df.copy()  # or df[columns_to_keep]

# Create the PairGrid
g = sns.PairGrid(new_df)

# Upper triangle: bivariate histogram
g.map_upper(sns.histplot, bins=20, pmax=0.9, cmap="Blues")

# Diagonal: histogram + KDE
g.map_diag(lambda x, **kwargs: sns.histplot(x, kde=True, edgecolor='black', **kwargs))

# Lower triangle: bivariate KDE
g.map_lower(sns.kdeplot, fill=True, cmap="Reds", thresh=0.05)

plt.show()